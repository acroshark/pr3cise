// Traducción con fallback a español
window.t = function(key) {
  const dict = window.translations[window.currentLang] || window.translations.es;
  return dict[key] !== undefined ? dict[key] : (window.translations.es[key] || key);
};

// Cambiar idioma: persiste en localStorage, actualiza DOM estático y re-renderiza
window.setLang = function(lang) {
  window.currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    el.innerHTML = window.t(k);
  });

  // Sincronizar el selector si el cambio viene de JS
  const sel = document.getElementById('lang-selector');
  if (sel && sel.value !== lang) sel.value = lang;

  if (window.budgetData && window.budgetData.info && typeof updateHeader === 'function') {
    updateHeader(window.budgetData.info);
  }
  if (typeof renderCurrentView === 'function') renderCurrentView();
};

// Inicialización al cargar el DOM
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('lang') || 'es';
  window.currentLang = saved;
  const sel = document.getElementById('lang-selector');
  if (sel) sel.value = saved;
  document.documentElement.lang = saved;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.innerHTML = window.t(el.getAttribute('data-i18n'));
  });
});
